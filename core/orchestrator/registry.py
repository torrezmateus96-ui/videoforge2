def get_lead_agent(lead_key: str) -> LeadAgentSpec:
    if lead_key not in LEAD_AGENT_REGISTRY:
        raise KeyError(f"Agente lider desconhecido: {lead_key}")
    return LEAD_AGENT_REGISTRY[lead_key]


def get_subagent(subagent_key: str) -> SubagentSpec:
    if subagent_key not in SUBAGENT_REGISTRY:
        raise KeyError(f"Subagente desconhecido: {subagent_key}")
    return SUBAGENT_REGISTRY[subagent_key]


def list_subagents_for_lead(lead_key: str) -> list[SubagentSpec]:
    get_lead_agent(lead_key)
    return [s for s in _SUBAGENTS_LIST if s.lead_key == lead_key]


